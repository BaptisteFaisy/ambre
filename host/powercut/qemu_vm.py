"""QEMU virtual machine control for the Ambre power-cut campaign (spec 7.4).

Single place where "how do we drive a guest machine" lives: the campaign
orchestrator, the E1 flush probe and the E3 cycle timer all use :class:`QemuVM`
and the helpers below, so probe/wait logic is never duplicated.

``qemu`` backend: real ``qemu-system-x86_64`` line — guest disk with
``cache=none`` and ``aio=native`` (ordered writes), optional ``blkdebug:`` error
injection, optional NBD drive served by ``faulty_block_server.py``, no network
(``-net none``: closed-loop EDR, VIE-03), serial console on a unix socket, QMP
socket.  ``dry-run`` backend: a fake-VM script replaces QEMU — it publishes the
events a real guest would have acquired before the cut (minus a configurable
"not yet durable" window) and dies when killed, so all logic is testable today.
``power_cut()`` sends SIGKILL: the guest stops instantly, as if power had been
removed. Known limitation (spec 7.4): writes already handed to the host survive;
this level tests ordering and interruption, not the loss of a volatile cache.
``faulty_block_server.py`` lifts that limitation.
"""

